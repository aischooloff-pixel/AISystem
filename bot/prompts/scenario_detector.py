"""Промпт определения сценария начала общения: A / B / C (Блок 4, функция 1).

Признаки и примеры — из таблицы ТЗ (источник: «Логика принятия решений AI»,
раздел 4). Сценарий определяется по первому содержательному сообщению.
"""

from __future__ import annotations

from bot.utils.validators import sanitize_user_text

SCENARIO_JSON_FORMAT = '{"scenario": "A_ready|B_problem|C_info", "confidence": 92, "reason": "..."}'

SCENARIO_PROMPT_TEMPLATE = """Определи сценарий начала общения по первому сообщению человека.

Сценарии:

1. A_ready — «Готовность записаться». Признаки: готовность записаться, вопрос о цене.
   Примеры: «Хочу записаться» · «Сколько стоит?» · «Как попасть на диагностику?» ·
   «Можно оплатить?» · «Хочу работать с Юлией»

2. B_problem — «Описывает проблему». Признаки: описание проблемы.
   Примеры: «У меня повторяется одна и та же ситуация» · «Не понимаю, почему всё рушится» ·
   «Постоянные конфликты» · «Не растёт бизнес» · «Не получается заработать»

3. C_info — «Информационный интерес». Признаки: информационный интерес.
   Примеры: «Что такое ITC?» · «Чем вы занимаетесь?» · «Расскажите о методе» ·
   «Что входит в диагностику?»

Правила:
- Если в сообщении одновременно и проблема, и готовность записаться — выбирай A_ready:
  готовность важнее (немедленная передача Юлии).
- confidence — целое число 0–100: насколько однозначно сообщение указывает на сценарий.
- reason — наблюдаемые признаки в сообщении, кратко, по-русски.

Сообщение человека:
\"\"\"{message}\"\"\"

Ответь строго JSON без пояснений, в формате:
{json_format}"""


def build_scenario_prompt(message: str) -> str:
    """Промпт определения сценария для конкретного сообщения."""
    return SCENARIO_PROMPT_TEMPLATE.format(
        message=sanitize_user_text(message), json_format=SCENARIO_JSON_FORMAT
    )
