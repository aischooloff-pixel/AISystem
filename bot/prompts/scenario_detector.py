"""Промпт определения сценария начала общения (Блок 4, функция 1).

Признаки и примеры — из ТЗ («Логика принятия решений AI», разделы 4, 8, 11).
Сценарий определяется по первому содержательному сообщению и решает, каким
путём пойдёт диалог, поэтому ошибка здесь ломает всё, что дальше.

Пять исходов, а не три. Прежняя редакция знала только A/B/C — и нецелевому
обращению просто не было куда деться: «погода на завтра» становилась C_info,
ответа в базе знаний не находилось, и клиент уходил Юлии как лид. Живой
прогон 20 сообщений 2026-07-28: 10 из 20 определены неверно, все нецелевые —
неверно. Нецелевые обращения (ТЗ, раздел 8) и отказ говорить с ботом
(«Обработка возражений», особый случай) теперь называются своими именами.
"""

from __future__ import annotations

from bot.utils.validators import sanitize_user_text

SCENARIO_JSON_FORMAT = (
    '{"scenario": "A_ready|B_problem|C_info|non_target|handoff", '
    '"confidence": 92, "reason": "..."}'
)

SCENARIO_PROMPT_TEMPLATE = """Определи сценарий начала общения по первому сообщению человека.

A_ready — «Готовность записаться». ТОЛЬКО при ЯВНОМ намерении записаться,
узнать цену или начать работу. Человек УЖЕ принял решение и хочет действовать.
  Примеры: «Хочу записаться» · «Сколько стоит?» · «Можно оплатить?» ·
  «Как попасть на диагностику?» · «Хочу работать с Юлией» · «Запишите меня» ·
  «Интересует диагностика» · «Сколько стоит сопровождение?»

B_problem — «Описывает проблему». Человек рассказывает о СВОЕЙ ситуации:
что происходит, что не получается, что повторяется. Явного намерения
записаться нет.
  Примеры: «У меня повторяется одна и та же ситуация» · «Не понимаю, почему
  всё рушится» · «Постоянные конфликты» · «Не растёт бизнес» · «Не могу выйти
  из состояния» · «Помогите разобраться» · «Я по рекомендации»

C_info — «Информационный интерес». Человек спрашивает О МЕТОДЕ, о бренде,
о формате работы — но не о своей ситуации и не о записи.
  Примеры: «Что такое ITC?» · «Расскажите о методе» · «Чем вы занимаетесь?» ·
  «Что входит в диагностику?» · «Как работает системная расстановка?» ·
  короткое приветствие без содержания: «Привет» · «Здравствуйте»

non_target — «Нецелевое обращение». Запрос ВООБЩЕ вне компетенции бренда
(ТЗ, раздел 8): медицинские вопросы · психиатрические состояния · экстренная
психологическая помощь · юридические консультации · налоговые вопросы ·
магические услуги · гадания · снятие порчи · запросы на быстрые чудеса ·
откровенный троллинг · спам · агрессия · бессмысленный набор символов.
  Примеры: «Погода на завтра» · «Снимите порчу» · «Мне нужен юрист» ·
  «Вопрос по психиатрии» · «Продайте мне биткоин» · «ааааааааа»

handoff — «Нужен живой человек». Человек отказывается говорить с ботом или
прямо просит связать его с Юлией лично.
  Примеры: «Не хочу с ботом» · «Можно с живым человеком?» · «Дайте контакт
  Юлии» · «Хочу поговорить с ней самой»

ПРАВИЛА:
- Не уверен между B_problem и C_info — выбирай B_problem: лишний вопрос
  не навредит, а пропущенный запрос — да.
- Не уверен между A_ready и B_problem — выбирай B_problem.
- non_target — ТОЛЬКО при ЯВНОМ несоответствии теме. Неясность,
  односложность или краткость сами по себе нецелевым обращением НЕ являются.
- Отказ от бота — это handoff, а НЕ non_target: человек целевой, ему просто
  нужен живой собеседник.
- Тяжёлое эмоциональное состояние, упоминание отчаяния, мыслей о смерти —
  это handoff, а НЕ non_target: такую ситуацию разбирает человек.
- Эмодзи, стикер или очень короткая реплика без смысла — C_info
  (переспросим), а не non_target.
- confidence — целое 0–100: насколько однозначно сообщение указывает
  на сценарий. Для non_target ставь высокий confidence только при явном
  несоответствии («погода на завтра» — 95+, «не знаю что сказать» — не
  non_target вовсе).
- reason — наблюдаемые признаки в сообщении, кратко, по-русски.

Сообщение человека:
\"\"\"{message}\"\"\"

Ответь строго JSON без пояснений, в формате:
{json_format}"""


def build_scenario_prompt(message: str) -> str:
    """Промпт определения сценария для конкретного сообщения."""
    return SCENARIO_PROMPT_TEMPLATE.format(
        message=sanitize_user_text(message), json_format=SCENARIO_JSON_FORMAT
    )
