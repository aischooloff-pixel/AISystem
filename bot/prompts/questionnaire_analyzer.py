"""Промпт разбора заполненной анкеты «Точка сбоя» → строгий JSON (Блок 11).

Границы жёсткие и заданы ТЗ дословно: «AI не проводит диагностику,
не интерпретирует ответы и не делает выводов о причинах ситуации».
Поэтому модель здесь только *сокращает и цитирует* сказанное клиентом:
выделяет основной запрос, собирает дословные формулировки и отмечает,
что стоит уточнить на встрече. Причины, гипотезы и вердикт — работа Юлии.

Сам отчёт Юлии собирается из ответов напрямую (см. ``services/notifier.py``):
вопросы 2/4/5 отвечают на «почему сейчас», «что пробовал», «чего хочет»
без участия модели. AI добавляет только резюме и темы для уточнения —
если он недоступен, отчёт всё равно уходит.
"""

from __future__ import annotations

from bot.utils.validators import sanitize_user_text

QUESTIONNAIRE_JSON_FORMAT = """{
  "main_request": "основной запрос словами клиента, 1 предложение",
  "summary": "нейтральное резюме ситуации, 2–3 предложения, без интерпретаций",
  "key_phrases": ["дословные цитаты клиента"],
  "preliminary_status": "hot|warm|cold|non_target",
  "topics_to_clarify": ["что стоит уточнить на встрече"],
  "confidence": 88
}"""

QUESTIONNAIRE_PROMPT_TEMPLATE = """Разбери анкету, которую клиент заполнил перед\
 системной диагностикой «Точка сбоя».

ЗАПРЕЩЕНО (граница из ТЗ, Блок 11):
- проводить диагностику и называть системную причину ситуации;
- интерпретировать ответы, строить гипотезы «почему так происходит»;
- делать психологические, медицинские, экспертные выводы;
- оценивать человека и давать советы;
- добавлять то, чего клиент не говорил.

Что нужно сделать — только это:
- main_request — основной запрос, максимально близко к словам клиента;
- summary — нейтральный пересказ ситуации без объяснения причин;
- key_phrases — дословные цитаты из ответов (3–6 штук), ничего не меняя;
- preliminary_status — ПРЕДВАРИТЕЛЬНАЯ оценка готовности по наблюдаемым
  признакам, окончательное решение принимает Юлия;
- topics_to_clarify — вопросы, которые стоит задать на встрече; это именно
  вопросы, а не выводы и не предположения о причинах;
- confidence — целое 0–100.

Ответы клиента на анкету:
{answers}

Ответь строго JSON без пояснений, в формате:
{json_format}"""

# Вопросы в том же порядке, что и в анкете (ТЗ, Блок 11).
FORM_LABELS: tuple[str, ...] = (
    "С какой ситуацией хочет разобраться",
    "Почему именно сейчас",
    "Что беспокоит сильнее всего",
    "Что уже пробовал(а)",
    "Какого результата хочет",
    "Почему важно решить именно это",
    "Что считает важным сообщить заранее",
)


def format_answers(answers: list[str]) -> str:
    """Ответы клиента → пронумерованный блок для промпта и отчёта."""
    lines = []
    for index, label in enumerate(FORM_LABELS):
        answer = answers[index] if index < len(answers) else ""
        lines.append(f"{index + 1}. {label}:\n{sanitize_user_text(answer) or '—'}")
    return "\n\n".join(lines)


def build_questionnaire_prompt(answers: list[str]) -> str:
    """Промпт разбора анкеты по семи ответам клиента."""
    return QUESTIONNAIRE_PROMPT_TEMPLATE.format(
        answers=format_answers(answers),
        json_format=QUESTIONNAIRE_JSON_FORMAT,
    )
